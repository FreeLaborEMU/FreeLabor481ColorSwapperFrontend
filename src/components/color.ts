export class Color {
    name: string;
    redValue: string;
    blueValue: string;
    greenValue: string;
    constructor(name: string, redValue: string, greenValue: string, blueValue: string) {
        this.name = name;
        this.redValue = redValue;
        this.greenValue = greenValue;
        this.blueValue = blueValue;
    }
}